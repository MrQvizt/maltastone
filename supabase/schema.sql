-- ---------- tables ----------

create table if not exists public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  cat text not null check (cat in ('crystals', 'jewellery', 'metaphysical', 'home')),
  sub text not null default '',
  name text not null check (length(trim(name)) > 0),
  price numeric(10, 2) not null check (price >= 0),
  stone text not null default '',
  intent text not null check (intent in ('calm', 'love', 'protection', 'clarity', 'grounding', 'abundance')),
  img text not null default '',
  "desc" text not null default '',
  best boolean not null default false,
  "new" boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.site_content (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_touch on public.products;
create trigger products_touch before update on public.products
  for each row execute function public.touch_updated_at();

drop trigger if exists site_content_touch on public.site_content;
create trigger site_content_touch before update on public.site_content
  for each row execute function public.touch_updated_at();

-- ---------- access rules ----------
-- Everyone can read visible products and site content.
-- Only signed-in users listed in public.admins can change anything.

alter table public.admins enable row level security;
alter table public.products enable row level security;
alter table public.site_content enable row level security;

revoke all on public.admins, public.products, public.site_content from anon, authenticated;
grant select on public.admins, public.products, public.site_content to anon, authenticated;
grant insert, update, delete on public.products, public.site_content to authenticated;

drop policy if exists "admins can see their own row" on public.admins;
create policy "admins can see their own row" on public.admins
  for select to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "anyone can read visible products" on public.products;
create policy "anyone can read visible products" on public.products
  for select to anon, authenticated
  using (active or exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

drop policy if exists "admins can add products" on public.products;
create policy "admins can add products" on public.products
  for insert to authenticated
  with check (exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

drop policy if exists "admins can edit products" on public.products;
create policy "admins can edit products" on public.products
  for update to authenticated
  using (exists (select 1 from public.admins a where a.user_id = (select auth.uid())))
  with check (exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

drop policy if exists "admins can delete products" on public.products;
create policy "admins can delete products" on public.products
  for delete to authenticated
  using (exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

drop policy if exists "anyone can read site content" on public.site_content;
create policy "anyone can read site content" on public.site_content
  for select to anon, authenticated
  using (true);

drop policy if exists "admins can add site content" on public.site_content;
create policy "admins can add site content" on public.site_content
  for insert to authenticated
  with check (exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

drop policy if exists "admins can edit site content" on public.site_content;
create policy "admins can edit site content" on public.site_content
  for update to authenticated
  using (exists (select 1 from public.admins a where a.user_id = (select auth.uid())))
  with check (exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

-- ---------- image storage ----------
-- Public bucket: anyone can view an image by its URL, only admins can upload.

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('images', 'images', true, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "admins can upload images" on storage.objects;
create policy "admins can upload images" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'images' and exists (select 1 from public.admins a where a.user_id = (select auth.uid())));

drop policy if exists "admins can remove images" on storage.objects;
create policy "admins can remove images" on storage.objects
  for delete to authenticated
  using (bucket_id = 'images' and exists (select 1 from public.admins a where a.user_id = (select auth.uid())));
